import React from "react";
import { Icon } from "../ui/Icon";

/** The unattended-origin marker on transcript messages (integrate-scheduler
 * chat spec; webhook kind rides add-webhook-channel-visibility 4.5): names
 * the schedule or webhook endpoint when known (runs-view context), generic
 * copy otherwise. */
export function SchedulerChip({ name, kind }: { name?: string; kind?: 'scheduler' | 'webhook' }) {
  const webhook = kind === 'webhook';
  return (
    <span className="inline-flex items-center gap-1 rounded-[5px] bg-[color-mix(in_oklab,var(--fg)_6%,transparent)] px-1.5 py-0.5 font-mono text-[10px] text-muted"
      title={name ? (webhook ? 'Invoked by the “' + name + '” webhook endpoint' : 'Generated by the “' + name + '” schedule') : webhook ? 'Invoked by a webhook delivery' : 'Generated by a scheduled run'}>
      <Icon name={webhook ? 'zap' : 'clock'} size={10}/> {name ? (webhook ? 'webhook · ' + name : 'scheduler · ' + name) : webhook ? 'Webhook run' : 'Scheduled run'}
    </span>
  );
}
